/**
 * Image generation via Pollinations — the free third-party route.
 *
 * NEVER call Gemini for image generation: every Gemini image model
 * is "Not available" on the free tier (unbilled projects get HTTP 429
 * `limit: 0`). Pollinations' legacy endpoint needs no key and no
 * signup, but it is a borrowed community lane, not infrastructure:
 *
 * - Model: Sana only. Output: JPEG with a small logo, max 768x768.
 * - Anonymous tier: ~1 new image per 40-45 s per IP. Faster requests
 *   get HTTP 402 + a `Retry-After` header — the route surfaces that
 *   as a 429 so the client can say "try again in Xs", not "broken".
 * - No uptime guarantee; the legacy endpoint could be retired.
 *   The route fails honestly (502 + plain words) when it is down.
 *
 * Architecture note: the route proxies the bytes through ANVIX, so
 * the 45 s/IP limit applies to the server's IP, shared by all users
 * — the per-user daily cap (10/day) is what keeps that lane usable
 * at this size. If traffic grows, the client should fetch the
 * Pollinations URL directly (CORS `*`) so the limit is per user IP.
 */

export const POLLINATIONS_BASE_URL = "https://image.pollinations.ai";
export const POLLINATIONS_MODEL = "sana";
export const POLLINATIONS_MAX_DIMENSION = 768;
export const POLLINATIONS_MAX_PROMPT_CHARS = 500;
export const POLLINATIONS_FETCH_TIMEOUT_MS = 60_000;

export const IMAGE_PROVIDER_NOTE =
  // ASCII only, on purpose: this string is also sent as the
  // X-ANVIX-Image-Note response header, and HTTP header values must
  // be ByteString (Latin-1). The em dash that used to sit here threw
  // "Cannot convert argument to a ByteString" in the route and the
  // image endpoint answered a bare 500 on every success (Vercel
  // runtime errors, 2026-11-27). Keep this Latin-1 safe.
  "Generated by a free community model (Pollinations / Sana) - quality varies, and the service may be slow or briefly unavailable.";

/** The canonical Pollinations URL for a prompt (also the cache key). */
export function buildPollinationsUrl(
  prompt: string,
  options: { width?: number; height?: number; seed?: number } = {}
): string {
  const width = clampDimension(options.width ?? POLLINATIONS_MAX_DIMENSION);
  const height = clampDimension(options.height ?? POLLINATIONS_MAX_DIMENSION);
  const params = new URLSearchParams({
    model: POLLINATIONS_MODEL,
    width: String(width),
    height: String(height),
    nologo: "false",
  });
  if (options.seed !== undefined) {
    params.set("seed", String(Math.trunc(options.seed)));
  }
  return `${POLLINATIONS_BASE_URL}/prompt/${encodeURIComponent(prompt)}?${params.toString()}`;
}

function clampDimension(value: number): number {
  if (!Number.isFinite(value)) return POLLINATIONS_MAX_DIMENSION;
  return Math.max(64, Math.min(POLLINATIONS_MAX_DIMENSION, Math.trunc(value)));
}

export type ImagePromptValidation =
  | { ok: true; prompt: string }
  | { ok: false; error: string };

/** Trim + validate a user-supplied image prompt. */
export function validateImagePrompt(value: unknown): ImagePromptValidation {
  if (typeof value !== "string" || !value.trim()) {
    return { ok: false, error: "Describe the image you want." };
  }
  const prompt = value.trim();
  if (prompt.length > POLLINATIONS_MAX_PROMPT_CHARS) {
    return {
      ok: false,
      error: `Keep the description under ${POLLINATIONS_MAX_PROMPT_CHARS} characters.`,
    };
  }
  return { ok: true, prompt };
}

/**
 * Parse a `Retry-After` header (seconds, or an HTTP date) into
 * seconds to wait. Defaults to 45 s — Pollinations' anonymous pace.
 */
export function parseRetryAfter(
  value: string | null,
  nowMs: number = Date.now()
): number {
  if (!value) return 45;
  const seconds = Number(value.trim());
  if (Number.isFinite(seconds) && seconds >= 0) {
    return Math.min(Math.ceil(seconds), 300);
  }
  const dateMs = Date.parse(value.trim());
  if (Number.isFinite(dateMs)) {
    return Math.max(1, Math.min(Math.ceil((dateMs - nowMs) / 1000), 300));
  }
  return 45;
}

/** Is this upstream status the Pollinations "slow down" signal? */
export function isPollinationsRateLimit(status: number): boolean {
  return status === 402 || status === 429;
}
